<?php
return function (\Illuminate\Http\Request $request): array {
    $pdo = \Illuminate\Support\Facades\DB::connection()->getPdo();



$themeCssVersion = filemtime(public_path('css/jftech-theme.css'));
$payrollCssVersion = filemtime(public_path('css/payroll.css'));
$clientFilterCssVersion = filemtime(public_path('css/client_filter.css'));

$success = '';
$error = '';


// A branch admin only works with their own branch's employees and payroll.
$scopeBranch = \App\Support\BranchScope::current();
[$employeeScope, $employeeScopeParams] = \App\Support\BranchScope::employees($scopeBranch, 'e');
[$payrollEmployeeScope, $payrollEmployeeScopeParams] = \App\Support\BranchScope::viaEmployee($scopeBranch, 'payroll.employee_id');

// Branch, barangay and employee search (the super admin may pick any branch; a branch admin only has their own). Left empty it
// shows every record the account may see. An employee has no barangay of their own, so it is looked up in the address.
$location = \App\Support\LocationFilter::fromRequest($request);
$branches = $location['branches'];
$branchBarangays = $location['branchBarangays'];
$selectedBranch = $location['selectedBranch'];
$selectedBarangays = $location['selectedBarangays'];
$searchTerm = $location['searchTerm'];
[$locationSql, $locationParams] = \App\Support\LocationFilter::employeeConditions($location, 'e');
// The same filter for queries on the payroll table itself.
$filteredEmployeeIds = "payroll.employee_id IN (SELECT e.id FROM employees e WHERE 1 = 1{$locationSql})";

$stmt = $pdo->prepare("SELECT e.id, e.employee_code, e.full_name, e.position, e.department, e.daily_rate, e.status, e.branch_name FROM employees e WHERE 1 = 1" . $employeeScope . " ORDER BY e.full_name");
$stmt->execute($employeeScopeParams);
$employees = $stmt->fetchAll();
$employeeMap = [];
foreach ($employees as $employee) {
    $employeeMap[$employee['id']] = $employee;
}
$hasEmployees = count($employees) > 0;

// A branch admin generates payroll for the technicians of their branch; the super admin generates it for the
// Admin employees (the branch admins). Everything else on this page is view-only, so nobody pays themselves.
$payrollEmployees = array_values(array_filter($employees, static fn (array $employee): bool => \App\Support\BranchScope::canManagePayrollFor($employee['position'])));
$payrollEmployeeMap = array_column($payrollEmployees, null, 'id');
$canGeneratePayroll = $payrollEmployees !== [];
$isSuperAdminPayroll = ! \App\Support\BranchScope::isRestricted();
$payrollRoleHint = $isSuperAdminPayroll
    ? 'The super admin generates payroll for the Admin employees only; the branch admins generate it for their technicians.'
    : 'Payroll for the Admin employees is generated by the super admin.';

// The position of the employee a payroll record belongs to; null when it is not in this branch.
$payrollRecordPosition = static function ($payrollId) use ($pdo, $payrollEmployeeScope, $payrollEmployeeScopeParams) {
    $stmt = $pdo->prepare("SELECT e.position FROM payroll JOIN employees e ON e.id = payroll.employee_id WHERE payroll.id = ?" . $payrollEmployeeScope);
    $stmt->execute([$payrollId, ...$payrollEmployeeScopeParams]);
    $position = $stmt->fetchColumn();

    return $position === false ? null : (string) $position;
};

$payroll = app(\App\Support\PayrollService::class);
$payrollSettings = $payroll->settings();
[$weekStart, $weekEnd] = $payroll->weekOf();

$validDate = static function (string $date): bool {
    return preg_match('/^\d{4}-\d{2}-\d{2}$/', $date) === 1 && checkdate((int) substr($date, 5, 2), (int) substr($date, 8, 2), (int) substr($date, 0, 4));
};

// The numbers a payroll would get from the daily rate and the attendance of a period: the payroll form shows them before saving.
if ($request->query('action') === 'preview') {
    $previewEmployee = (int) $request->query('employee_id');
    $previewStart = (string) $request->query('start');
    $previewEnd = (string) $request->query('end');
    if (!$previewEmployee || !isset($employeeMap[$previewEmployee]) || !$validDate($previewStart) || !$validDate($previewEnd) || $previewEnd < $previewStart) {
        throw new \Illuminate\Http\Exceptions\HttpResponseException(response()->json(['success' => false, 'message' => 'Choose an employee and a valid period.'], 422));
    }
    $lines = $payroll->compute($previewEmployee, (float) $employeeMap[$previewEmployee]['daily_rate'], $previewStart, $previewEnd);
    throw new \Illuminate\Http\Exceptions\HttpResponseException(response()->json(['success' => true] + $lines));
}

// Automatic payroll for a whole week: every employee this account may pay, worked out from the daily rate and the attendance.
if ($request->isMethod('post') && $request->input('payroll_action') === 'auto_generate') {
    try {
        if (!$canGeneratePayroll) {
            throw new Exception($payrollRoleHint);
        }
        $weekDate = (string) $request->input('week_date');
        if (!$validDate($weekDate)) {
            throw new Exception('Choose a date in the week to generate payroll for.');
        }

        $result = $payroll->generateForWeek(\Carbon\Carbon::parse($weekDate), array_map('intval', array_column($payrollEmployees, 'id')));
        $parts = [$result['created'] . ' created'];
        if ($result['existing'] > 0) {
            $parts[] = $result['existing'] . ' already had payroll';
        }
        if ($result['no_attendance'] > 0) {
            $parts[] = $result['no_attendance'] . ' had no attendance';
        }
        if ($result['no_rate'] > 0) {
            $parts[] = $result['no_rate'] . ' have no daily rate';
        }
        $success = 'Automatic payroll for ' . date('M d', strtotime($result['period_start'])) . ' - ' . date('M d, Y', strtotime($result['period_end'])) . ': ' . implode(', ', $parts) . '.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
} elseif ($request->isMethod('post')) {
    try {
        $payrollId = $request->input('payroll_id') ?? null;
        $employeeId = (int) ($request->input('employee_id') ?? 0);
        $periodStart = (string) ($request->input('payroll_period_start') ?? '');
        $periodEnd = (string) ($request->input('payroll_period_end') ?? '');
        $status = $request->input('status') ?? 'draft';

        if (!$employeeId || !isset($employeeMap[$employeeId])) {
            throw new Exception('Please select a valid employee.');
        }
        if (!isset($payrollEmployeeMap[$employeeId])) {
            throw new Exception($payrollRoleHint);
        }
        // Editing a record: it must already belong to an employee of this branch that this account may pay.
        if ($payrollId) {
            $recordPosition = $payrollRecordPosition($payrollId);
            if ($recordPosition === null) {
                throw new Exception('That payroll record does not belong to your branch.');
            }
            if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
                throw new Exception($payrollRoleHint);
            }
        }
        $dailyRate = (float) $employeeMap[$employeeId]['daily_rate'];

        if (!$periodStart || !$periodEnd) {
            throw new Exception('Payroll period start and end dates are required.');
        }
        if (!$validDate($periodStart) || !$validDate($periodEnd)) {
            throw new Exception('Enter the payroll period as valid dates.');
        }
        if ($periodEnd < $periodStart) {
            throw new Exception('Payroll period end date cannot be earlier than the start date.');
        }

        $allowedStatuses = ['draft', 'processed', 'paid'];
        if (!in_array($status, $allowedStatuses, true)) {
            $status = 'draft';
        }

        if ($dailyRate <= 0) {
            throw new Exception('Please enter a valid daily rate for the selected employee.');
        }

        $labels = [
            'total_days_worked' => 'Days worked', 'late_minutes' => 'Late minutes', 'undertime_minutes' => 'Undertime minutes', 'overtime_hours' => 'Overtime hours',
            'basic_salary' => 'Basic salary', 'overtime_pay' => 'Overtime pay', 'late' => 'Late', 'undertime' => 'Undertime', 'absent' => 'Absent',
            'sss' => 'SSS', 'philhealth' => 'PhilHealth', 'pagibig' => 'Pag-IBIG',
            'regular_holiday' => 'Regular holiday', 'special_holiday' => 'Special holiday', 'night_differential' => 'Night differential',
            'incentives' => 'Incentives', 'allowances' => 'Allowances', 'leave_pay' => 'Leave pay', 'rest_day_pay' => 'Rest day pay',
            'salary_adjustment' => 'Salary adjustment', 'other_earnings' => 'Other earnings',
            'withholding_tax' => 'Withholding tax', 'cash_advance' => 'Cash advance', 'salary_loan' => 'Salary loan', 'hdmf_loan' => 'HDMF loan', 'other_deductions' => 'Other deductions',
        ];
        // A number the admin typed, or null when the field was left empty.
        $typed = static function (string $key) use ($request, $labels): ?float {
            $raw = $request->input($key);
            if ($raw === null || trim((string) $raw) === '') {
                return null;
            }
            if (!is_numeric($raw)) {
                throw new Exception($labels[$key] . ' must be a number.');
            }
            $value = max(0, (float) $raw);
            if ($value > 999999.99) {
                throw new Exception($labels[$key] . ' is too large.');
            }

            return $value;
        };

        $mode = $request->input('computation_mode') === 'manual' ? 'manual' : 'auto';

        // Undertime is not tracked by the clock, so its minutes are typed in both modes.
        $override = ['undertime_minutes' => $typed('undertime_minutes') ?? 0];
        if ($mode === 'manual') {
            $periodDays = (int) round((strtotime($periodEnd) - strtotime($periodStart)) / 86400) + 1;
            $days = $typed('total_days_worked');
            if ($days !== null && $days > $periodDays) {
                throw new Exception('Days worked cannot be more than the ' . $periodDays . ' day(s) of the period.');
            }
            $overtimeHours = $typed('overtime_hours');
            $quantities = ['days_worked' => $days, 'late_minutes' => $typed('late_minutes'), 'overtime_minutes' => $overtimeHours === null ? null : $overtimeHours * 60];
            foreach ($quantities as $key => $value) {
                if ($value !== null) {
                    $override[$key] = $value;
                }
            }
        }

        $lines = $payroll->compute($employeeId, $dailyRate, $periodStart, $periodEnd, $override);
        if ($mode === 'auto' && $lines['total_days_worked'] <= 0 && $lines['overtime_hours'] <= 0) {
            throw new Exception($employeeMap[$employeeId]['full_name'] . ' has no attendance in this period, so there is nothing to compute. Record the attendance first, or choose Manual to enter the pay by hand.');
        }
        if ($mode === 'manual') {
            // Whatever the admin typed over a computed amount wins; an empty field keeps the standard computation.
            foreach (\App\Support\PayrollCalculator::COMPUTED as $key) {
                $value = $typed($key);
                if ($value !== null) {
                    $lines[$key] = $value;
                }
            }
        }

        $extras = [];
        foreach (array_merge(\App\Support\PayrollCalculator::EXTRA_EARNINGS, \App\Support\PayrollCalculator::EXTRA_DEDUCTIONS) as $key) {
            $extras[$key] = $typed($key) ?? 0.0;
        }

        // One payroll per employee and period; a second one would pay the same days twice.
        $duplicate = \Illuminate\Support\Facades\DB::table('payroll')
            ->where('employee_id', $employeeId)->where('payroll_period_start', $periodStart)->where('payroll_period_end', $periodEnd)
            ->whereRaw('(archived = 0 OR archived IS NULL)')
            ->when($payrollId, fn ($query) => $query->where('id', '!=', $payrollId))->exists();
        if ($duplicate) {
            throw new Exception($employeeMap[$employeeId]['full_name'] . ' already has payroll for this period. Edit that record instead.');
        }

        $columns = $payroll->row($employeeId, $dailyRate, $periodStart, $periodEnd, $lines, $extras, $mode, $status);

        if ($payrollId) {
            \Illuminate\Support\Facades\DB::table('payroll')->where('id', $payrollId)->update($columns);
            $success = 'Payroll record updated successfully.';
        } else {
            \Illuminate\Support\Facades\DB::table('payroll')->insert($columns + ['created_at' => now()]);
            $success = 'Payroll record created successfully.';
        }
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

$view = $request->query('view') ?? '';
$showArchived = $view === 'archived';

if ($request->has('delete') && $request->query('delete')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('delete'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("UPDATE payroll SET archived = 1 WHERE id = ?" . $payrollEmployeeScope);
        $stmt->execute([$request->query('delete'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record archived successfully.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

if ($request->has('restore') && $request->query('restore')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('restore'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("UPDATE payroll SET archived = 0 WHERE id = ?" . $payrollEmployeeScope);
        $stmt->execute([$request->query('restore'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record restored successfully.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

if ($request->has('purge') && $request->query('purge')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('purge'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("DELETE FROM payroll WHERE id = ? AND archived = 1" . $payrollEmployeeScope);
        $stmt->execute([$request->query('purge'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record permanently deleted.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

$where = [];
$params = [];

if ($employeeScope !== '') {
    $where[] = substr($employeeScope, strlen(' AND '));
    array_push($params, ...$employeeScopeParams);
}

if ($locationSql !== '') {
    $where[] = substr($locationSql, strlen(' AND '));
    array_push($params, ...$locationParams);
}

if ($showArchived) {
    $where[] = 'p.archived = 1';
} else {
    $where[] = '(p.archived = 0 OR p.archived IS NULL)';
}

$payrollSql = "
    SELECT p.*, e.full_name AS employee_name, e.employee_code, e.position, e.department, e.branch_name, e.status AS employment_status
    FROM payroll p
    JOIN employees e ON p.employee_id = e.id
";

if ($where) {
    $payrollSql .= ' WHERE ' . implode(' AND ', $where);
}

$payrollSql .= ' ORDER BY p.created_at DESC, p.payroll_period_end DESC';

$stmt = $pdo->prepare($payrollSql);
$stmt->execute($params);
$payrollRecords = $stmt->fetchAll();
foreach ($payrollRecords as &$payrollRecord) {
    $payrollRecord['can_manage'] = \App\Support\BranchScope::canManagePayrollFor($payrollRecord['position'] ?? null);
}
unset($payrollRecord);

$statStmt = $pdo->prepare("
    SELECT
        COUNT(*) AS total,
        COALESCE(SUM(net_pay), 0) AS net,
        SUM(CASE WHEN status = 'processed' THEN 1 ELSE 0 END) AS processed,
        SUM(CASE WHEN status = 'paid' THEN 1 ELSE 0 END) AS paid
    FROM payroll
    WHERE (archived = 0 OR archived IS NULL)" . $payrollEmployeeScope . ' AND ' . $filteredEmployeeIds);
$statStmt->execute([...$payrollEmployeeScopeParams, ...$locationParams]);
$stats = $statStmt->fetch();
$archivedStmt = $pdo->prepare("SELECT COUNT(*) FROM payroll WHERE archived = 1" . $payrollEmployeeScope . ' AND ' . $filteredEmployeeIds);
$archivedStmt->execute([...$payrollEmployeeScopeParams, ...$locationParams]);
$archivedCount = (int) $archivedStmt->fetchColumn();

$totalRecords = (int) $stats['total'];
$totalNetPay = (float) $stats['net'];
$processedCount = (int) $stats['processed'];
$paidCount = (int) $stats['paid'];

$payrollConfig = [
    'hoursPerDay' => $payrollSettings['hours_per_day'],
    'overtimeRate' => $payrollSettings['overtime_rate'],
    'daysPerMonth' => $payrollSettings['days_per_month'],
];
$eligibleCount = count($payrollEmployees);

// The employees the payroll form suggests while typing: only the ones this account pays (a branch admin: the technicians of their
// branch; the super admin: the Admin employees of every branch, so the branch is part of the text they can search).
$employeeChoices = array_map(static fn (array $employee): array => [
    'id' => (int) $employee['id'],
    'label' => $employee['full_name'] . ' - ' . $employee['employee_code'] . ($isSuperAdminPayroll ? ' · ' . ($employee['branch_name'] ?: 'No branch') : ''),
], $payrollEmployees);

$employeeJson = json_encode(
    array_values($employees),
    JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT
);
    return get_defined_vars();
};
