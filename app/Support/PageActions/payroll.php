<?php
return function (\Illuminate\Http\Request $request): array {
    $pdo = \Illuminate\Support\Facades\DB::connection()->getPdo();



$themeCssVersion = filemtime(public_path('css/jftech-theme.css'));
$payrollCssVersion = filemtime(public_path('css/payroll.css'));

$success = '';
$error = '';

$selectedEmployee = $request->query('employee_id') ?? '';
$selectedStatus = $request->query('status') ?? '';
$selectedStart = $request->query('period_start') ?? '';
$selectedEnd = $request->query('period_end') ?? '';

// A branch admin only works with their own branch's employees and payroll.
$scopeBranch = \App\Support\BranchScope::current();
[$employeeScope, $employeeScopeParams] = \App\Support\BranchScope::employees($scopeBranch, 'e');
[$payrollEmployeeScope, $payrollEmployeeScopeParams] = \App\Support\BranchScope::viaEmployee($scopeBranch, 'payroll.employee_id');

$stmt = $pdo->prepare("SELECT e.id, e.employee_code, e.full_name, e.position, e.department, e.daily_rate, e.status FROM employees e WHERE 1 = 1" . $employeeScope . " ORDER BY e.full_name");
$stmt->execute($employeeScopeParams);
$employees = $stmt->fetchAll();

$employeeMap = [];
foreach ($employees as $employee) {
    $employeeMap[$employee['id']] = $employee;
}
$hasEmployees = count($employees) > 0;

// A branch admin generates payroll for the technicians of their branch; the super admin generates it for the
// Admin employees (the branch admins). Everything else on this page is view-only, so nobody pays themselves.
$payrollEmployees = array_values(array_filter($employees, static fn (array $employee): bool => \App\Support\BranchScope::canManagePayrollFor($employee['position'])));
$payrollEmployeeMap = array_column($payrollEmployees, null, 'id');
$canGeneratePayroll = $payrollEmployees !== [];
$isSuperAdminPayroll = ! \App\Support\BranchScope::isRestricted();
$payrollRoleHint = $isSuperAdminPayroll
    ? 'The super admin generates payroll for the Admin employees only; the branch admins generate it for their technicians.'
    : 'Payroll for the Admin employees is generated by the super admin.';

// The position of the employee a payroll record belongs to; null when it is not in this branch.
$payrollRecordPosition = static function ($payrollId) use ($pdo, $payrollEmployeeScope, $payrollEmployeeScopeParams) {
    $stmt = $pdo->prepare("SELECT e.position FROM payroll JOIN employees e ON e.id = payroll.employee_id WHERE payroll.id = ?" . $payrollEmployeeScope);
    $stmt->execute([$payrollId, ...$payrollEmployeeScopeParams]);
    $position = $stmt->fetchColumn();

    return $position === false ? null : (string) $position;
};

$deductionSettings = $pdo->query("SELECT setting_key, setting_value FROM system_settings WHERE setting_key IN ('payroll_500_sss', 'payroll_500_philhealth', 'payroll_500_pagibig', 'payroll_580_sss', 'payroll_580_philhealth', 'payroll_580_pagibig', 'payroll_600_sss', 'payroll_600_philhealth', 'payroll_600_pagibig')")
    ->fetchAll(\PDO::FETCH_KEY_PAIR);

function weeklyStatutoryDeductions(float $dailyRate, array $settings): array {
    $rateKey = (string) (int) round($dailyRate);
    if (! in_array($rateKey, ['500', '580', '600'], true)) {
        return ['sss' => 0, 'philhealth' => 0, 'pagibig' => 0];
    }

    return [
        'sss' => (float) ($settings["payroll_{$rateKey}_sss"] ?? 0),
        'philhealth' => (float) ($settings["payroll_{$rateKey}_philhealth"] ?? 0),
        'pagibig' => (float) ($settings["payroll_{$rateKey}_pagibig"] ?? 0),
    ];
}

function attendancePayrollSummary($pdo, int $employeeId, string $periodStart, string $periodEnd, float $dailyRate): array {
    $attendance = getAttendanceDays($pdo, $employeeId, $periodStart, $periodEnd);
    $stmt = $pdo->prepare("SELECT SUM(CASE WHEN status_morning = 'late' THEN 1 ELSE 0 END) + SUM(CASE WHEN status_afternoon = 'late' THEN 1 ELSE 0 END) AS late_count, SUM(CASE WHEN status_morning = 'absent' THEN 1 ELSE 0 END) + SUM(CASE WHEN status_afternoon = 'absent' THEN 1 ELSE 0 END) AS absent_count FROM attendance WHERE employee_id = ? AND attendance_date BETWEEN ? AND ?");
    $stmt->execute([$employeeId, $periodStart, $periodEnd]);
    $counts = $stmt->fetch() ?: [];

    return [
        'days_worked' => (int) ($attendance['days_worked'] ?? 0),
        'total_hours' => (float) ($attendance['total_hours'] ?? 0),
        'late_count' => (int) ($counts['late_count'] ?? 0),
        'absent_count' => (int) ($counts['absent_count'] ?? 0),
        'late_amount' => (int) ($counts['late_count'] ?? 0) * ($dailyRate / 8),
        'absent_amount' => (int) ($counts['absent_count'] ?? 0) * ($dailyRate / 2),
    ];
}

function getAttendanceDays($pdo, $employeeId, $periodStart, $periodEnd) {
    $stmt = $pdo->prepare("
        SELECT
            COUNT(
                CASE
                    WHEN COALESCE(total_hours, 0) > 0
                         OR morning_time_in IS NOT NULL
                         OR afternoon_time_in IS NOT NULL
                    THEN 1
                END
            ) AS days_worked,
            COALESCE(SUM(total_hours), 0) AS total_hours
        FROM attendance
        WHERE employee_id = ?
          AND attendance_date BETWEEN ? AND ?
    ");
    $stmt->execute([$employeeId, $periodStart, $periodEnd]);
    return $stmt->fetch();
}

if ($request->has('action') && $request->query('action') === 'attendance') {
    header('Content-Type: application/json');
    $empId = (int) ($request->query('employee_id') ?? 0);
    $start = $request->query('start') ?? '';
    $end = $request->query('end') ?? '';
    if ($empId && $start && $end && isset($employeeMap[$empId])) {
        $empStmt = $pdo->prepare("SELECT daily_rate FROM employees WHERE id = ?");
        $empStmt->execute([$empId]);
        $emp = $empStmt->fetch();
        $dailyRate = (float) ($emp['daily_rate'] ?? 0);
        $summary = attendancePayrollSummary($pdo, $empId, $start, $end, $dailyRate);
        $statutory = weeklyStatutoryDeductions($dailyRate, $deductionSettings);
        echo json_encode([
            ...$summary,
            ...$statutory,
        ]);
    } else {
        echo json_encode(['days_worked' => 0, 'total_hours' => 0, 'late_count' => 0, 'absent_count' => 0, 'late_amount' => 0, 'absent_amount' => 0]);
    }
    exit;
}

if ($request->isMethod('post')) {
    try {
        $payrollId = $request->input('payroll_id') ?? null;
        $employeeId = (int) ($request->input('employee_id') ?? 0);
        $periodStart = $request->input('payroll_period_start') ?? '';
        $periodEnd = $request->input('payroll_period_end') ?? '';
        $status = $request->input('status') ?? 'draft';

        if (!$employeeId || !isset($employeeMap[$employeeId])) {
            throw new Exception('Please select a valid employee.');
        }
        if (!isset($payrollEmployeeMap[$employeeId])) {
            throw new Exception($payrollRoleHint);
        }
        // Editing a record: it must already belong to an employee of this branch that this account may pay.
        if ($payrollId) {
            $recordPosition = $payrollRecordPosition($payrollId);
            if ($recordPosition === null) {
                throw new Exception('That payroll record does not belong to your branch.');
            }
            if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
                throw new Exception($payrollRoleHint);
            }
        }
        $dailyRate = (float) $employeeMap[$employeeId]['daily_rate'];

        if (!$periodStart || !$periodEnd) {
            throw new Exception('Payroll period start and end dates are required.');
        }

        if ($periodEnd < $periodStart) {
            throw new Exception('Payroll period end date cannot be earlier than the start date.');
        }

        $allowedStatuses = ['draft', 'processed', 'paid'];
        if (!in_array($status, $allowedStatuses, true)) {
            $status = 'draft';
        }

        if ($dailyRate <= 0) {
            throw new Exception('Please enter a valid daily rate for the selected employee.');
        }

        $earningsKeys = [
            'basic_salary', 'overtime_pay', 'regular_holiday', 'special_holiday', 'night_differential',
            'incentives', 'allowances', 'leave_pay', 'rest_day_pay', 'salary_adjustment', 'other_earnings'
        ];
        $deductionKeys = [
            'sss', 'philhealth', 'pagibig', 'withholding_tax', 'cash_advance', 'salary_loan', 'hdmf_loan', 'other_deductions'
        ];
        $inputKeys = array_merge(['overtime_hours', 'late', 'undertime', 'absent'], $earningsKeys, $deductionKeys);

        $input = [];
        foreach ($inputKeys as $key) {
            $input[$key] = max(0, (float) ($request->input($key) ?? 0));
        }

        $attendanceSummary = attendancePayrollSummary($pdo, $employeeId, $periodStart, $periodEnd, $dailyRate);
        $daysWorked = $attendanceSummary['days_worked'];
        $totalHours = $attendanceSummary['total_hours'];

        $monthlyBasic = $dailyRate * 26;
        $hourlyRate = $dailyRate / 8;

        $input['basic_salary'] = $daysWorked * $dailyRate;
        $input['late'] = $attendanceSummary['late_amount'];
        $input['absent'] = $attendanceSummary['absent_amount'];
        $statutory = weeklyStatutoryDeductions($dailyRate, $deductionSettings);
        $input['sss'] = $statutory['sss'];
        $input['philhealth'] = $statutory['philhealth'];
        $input['pagibig'] = $statutory['pagibig'];

        $grossPay = 0;
        foreach ($earningsKeys as $key) {
            $grossPay += $input[$key];
        }
        $totalDeductions = 0;
        foreach ($deductionKeys as $key) {
            $totalDeductions += $input[$key];
        }
        $netPay = max(0, $grossPay - $totalDeductions);

        $columns = [
            'employee_id' => $employeeId,
            'payroll_period_start' => $periodStart,
            'payroll_period_end' => $periodEnd,
            'total_days_worked' => $daysWorked,
            'total_hours' => $totalHours,
            'daily_rate' => $dailyRate,
            'monthly_basic_salary' => $monthlyBasic,
            'hourly_rate' => $hourlyRate,
            'overtime_hours' => $input['overtime_hours'],
            'late' => $input['late'],
            'undertime' => $input['undertime'],
            'absent' => $input['absent'],
            'basic_salary' => $input['basic_salary'],
            'overtime_pay' => $input['overtime_pay'],
            'regular_holiday' => $input['regular_holiday'],
            'special_holiday' => $input['special_holiday'],
            'night_differential' => $input['night_differential'],
            'incentives' => $input['incentives'],
            'allowances' => $input['allowances'],
            'leave_pay' => $input['leave_pay'],
            'rest_day_pay' => $input['rest_day_pay'],
            'salary_adjustment' => $input['salary_adjustment'],
            'other_earnings' => $input['other_earnings'],
            'gross_pay' => $grossPay,
            'sss' => $input['sss'],
            'philhealth' => $input['philhealth'],
            'pagibig' => $input['pagibig'],
            'withholding_tax' => $input['withholding_tax'],
            'cash_advance' => $input['cash_advance'],
            'salary_loan' => $input['salary_loan'],
            'hdmf_loan' => $input['hdmf_loan'],
            'other_deductions' => $input['other_deductions'],
            'deductions' => $totalDeductions,
            'net_pay' => $netPay,
            'status' => $status,
        ];

        $colNames = array_keys($columns);
        $colValues = array_values($columns);

        if ($payrollId) {
            $setParts = array_map(function ($c) { return "$c = ?"; }, $colNames);
            $stmt = $pdo->prepare("UPDATE payroll SET " . implode(', ', $setParts) . " WHERE id = ?");
            $stmt->execute(array_merge($colValues, [$payrollId]));
            $success = 'Payroll record updated successfully.';
        } else {
            $placeholders = array_fill(0, count($colNames), '?');
            $stmt = $pdo->prepare("INSERT INTO payroll (" . implode(', ', $colNames) . ") VALUES (" . implode(', ', $placeholders) . ")");
            $stmt->execute($colValues);
            $success = 'Payroll record created successfully.';
        }
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

$view = $request->query('view') ?? '';
$showArchived = $view === 'archived';

if ($request->has('delete') && $request->query('delete')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('delete'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("UPDATE payroll SET archived = 1 WHERE id = ?" . $payrollEmployeeScope);
        $stmt->execute([$request->query('delete'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record archived successfully.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

if ($request->has('restore') && $request->query('restore')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('restore'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("UPDATE payroll SET archived = 0 WHERE id = ?" . $payrollEmployeeScope);
        $stmt->execute([$request->query('restore'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record restored successfully.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

if ($request->has('purge') && $request->query('purge')) {
    try {
        $recordPosition = $payrollRecordPosition($request->query('purge'));
        if ($recordPosition === null) {
            throw new Exception('Payroll record not found.');
        }
        if (!\App\Support\BranchScope::canManagePayrollFor($recordPosition)) {
            throw new Exception($payrollRoleHint);
        }
        $stmt = $pdo->prepare("DELETE FROM payroll WHERE id = ? AND archived = 1" . $payrollEmployeeScope);
        $stmt->execute([$request->query('purge'), ...$payrollEmployeeScopeParams]);
        $success = 'Payroll record permanently deleted.';
    } catch (Exception $e) {
        $error = 'Error: ' . $e->getMessage();
    }
}

$where = [];
$params = [];

if ($employeeScope !== '') {
    $where[] = substr($employeeScope, strlen(' AND '));
    array_push($params, ...$employeeScopeParams);
}

if ($selectedEmployee !== '') {
    $where[] = 'p.employee_id = ?';
    $params[] = $selectedEmployee;
}

if ($selectedStatus !== '') {
    $where[] = 'p.status = ?';
    $params[] = $selectedStatus;
}

if ($selectedStart !== '') {
    $where[] = 'p.payroll_period_start >= ?';
    $params[] = $selectedStart;
}

if ($selectedEnd !== '') {
    $where[] = 'p.payroll_period_end <= ?';
    $params[] = $selectedEnd;
}

if ($showArchived) {
    $where[] = 'p.archived = 1';
} else {
    $where[] = '(p.archived = 0 OR p.archived IS NULL)';
}

$payrollSql = "
    SELECT p.*, e.full_name AS employee_name, e.employee_code, e.position, e.department, e.status AS employment_status
    FROM payroll p
    JOIN employees e ON p.employee_id = e.id
";

if ($where) {
    $payrollSql .= ' WHERE ' . implode(' AND ', $where);
}

$payrollSql .= ' ORDER BY p.created_at DESC, p.payroll_period_end DESC';

$stmt = $pdo->prepare($payrollSql);
$stmt->execute($params);
$payrollRecords = $stmt->fetchAll();
foreach ($payrollRecords as &$payrollRecord) {
    $payrollRecord['can_manage'] = \App\Support\BranchScope::canManagePayrollFor($payrollRecord['position'] ?? null);
}
unset($payrollRecord);

$statStmt = $pdo->prepare("
    SELECT
        COUNT(*) AS total,
        COALESCE(SUM(net_pay), 0) AS net,
        SUM(CASE WHEN status = 'processed' THEN 1 ELSE 0 END) AS processed,
        SUM(CASE WHEN status = 'paid' THEN 1 ELSE 0 END) AS paid
    FROM payroll
    WHERE (archived = 0 OR archived IS NULL)" . $payrollEmployeeScope);
$statStmt->execute($payrollEmployeeScopeParams);
$stats = $statStmt->fetch();
$archivedStmt = $pdo->prepare("SELECT COUNT(*) FROM payroll WHERE archived = 1" . $payrollEmployeeScope);
$archivedStmt->execute($payrollEmployeeScopeParams);
$archivedCount = (int) $archivedStmt->fetchColumn();

$totalRecords = (int) $stats['total'];
$totalNetPay = (float) $stats['net'];
$processedCount = (int) $stats['processed'];
$paidCount = (int) $stats['paid'];

$employeeJson = json_encode(
    array_values($employees),
    JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT
);
    return get_defined_vars();
};
