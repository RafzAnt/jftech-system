{{--
    The standard printed report of the system. A report view extends this and sets, before its content:
      $reportTitle     the title, e.g. 'Payment Transactions Report' (also the name of the saved PDF)
      $documentTitle   optional; the name of the saved PDF when it should differ from the title, e.g. 'Payslip - Ana Reyes'
      $reportCoverage  the line under the title, e.g. ReportFormat::coverage($from, $to)
      $reportBranch    optional; defaults to the branch of the signed-in admin ("All Branches" for the super admin)
      $reportDetails   optional ['Status' => 'Paid Bills'] shown beside the branch
      $orientation     'landscape' (default) or 'portrait'
      $signatories     optional [['role' => 'Prepared by', 'name' => '', 'title' => '', 'caption' => '']]
      $endOf           optional; what ends in "*** END OF REPORT ***", e.g. 'Payslip'
      $printDelay      optional milliseconds to wait before the print dialog opens
    and puts its tables in @section('content'). Extra scripts and styles go in @push('head') and @push('scripts').
--}}
@use('App\Support\ReportFormat')
@php
    $company = config('company');
    $orientation = $orientation ?? 'landscape';
    $preparedBy = ReportFormat::preparedBy();
    $printedAt = ReportFormat::dateTime(now());
    $printedBy = $preparedBy['name'] !== '' ? $preparedBy['name'] : 'System';
    $signatories = $signatories ?? [
        ['role' => 'Prepared by', 'name' => $preparedBy['name'], 'title' => $preparedBy['title']],
        ['role' => 'Checked by'],
        ['role' => 'Approved by', 'name' => $company['approver']['name'], 'title' => $company['approver']['title']],
    ];
    $logoPath = resource_path('views/logo/jftect_logo.png');
    $logoData = is_file($logoPath) ? base64_encode(file_get_contents($logoPath)) : null;
@endphp
<!DOCTYPE html>
<html lang="en-PH">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{{ $documentTitle ?? $reportTitle }}</title>
    <link rel="stylesheet" href="{{ asset('css/print_report.css') }}?{{ @filemtime(public_path('css/print_report.css')) ?: 1 }}">
    <style>
        @page {
            size: A4 {{ $orientation }};
            margin: 14mm 12mm 18mm;
            @bottom-left { content: "{!! ReportFormat::cssString($reportTitle) !!}"; font: 8pt Arial, Helvetica, sans-serif; color: #444; }
            @bottom-center { content: "Printed {!! ReportFormat::cssString($printedAt . ' by ' . $printedBy) !!}"; font: 8pt Arial, Helvetica, sans-serif; color: #444; }
            @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 8pt Arial, Helvetica, sans-serif; color: #444; }
        }
    </style>
    @stack('head')
</head>
<body class="report-doc {{ $orientation }}">
    <div class="toolbar"><button type="button" onclick="window.print()">Print / Save as PDF</button></div>

    <main class="report">
        <header class="letterhead">
            @if ($logoData)
                <img src="data:image/png;base64,{{ $logoData }}" alt="{{ $company['name'] }} logo">
            @endif
            <div>
                <div class="company-name">{{ $company['name'] }}</div>
                <div class="company-line">{{ $company['address'] }}</div>
                <div class="company-line">{{ $company['email'] }} &nbsp;|&nbsp; TIN: {{ $company['tin'] }}</div>
            </div>
        </header>

        <div class="report-title">
            <h1>{{ $reportTitle }}</h1>
            <div class="coverage">{{ $reportCoverage }}</div>
        </div>

        <div class="report-info">
            <div><span>Branch:</span><strong>{{ $reportBranch ?? ReportFormat::branch() }}</strong></div>
            @foreach ($reportDetails ?? [] as $label => $value)
                <div><span>{{ $label }}:</span><strong>{{ $value }}</strong></div>
            @endforeach
            <div><span>Date generated:</span><strong>{{ $printedAt }}</strong></div>
        </div>

        @yield('content')

        <section class="signatories">
            @foreach ($signatories as $signatory)
                <div class="signatory">
                    <div class="role">{{ $signatory['role'] }}:</div>
                    <div class="name">{{ $signatory['name'] ?? '' }}</div>
                    <div class="caption">Signature over printed name</div>
                    @if (! empty($signatory['title']))
                        <div class="title">{{ $signatory['title'] }}</div>
                    @endif
                    <div class="signed-on">Date: ______________________</div>
                </div>
            @endforeach
        </section>

        <footer class="report-end">
            <div class="end-mark">*** END OF {{ strtoupper($endOf ?? 'Report') }} ***</div>
            <div>System-generated by {{ $company['system'] }}. Printed {{ $printedAt }} by {{ $printedBy }}.</div>
        </footer>
    </main>

    @stack('scripts')
    <script>
        window.addEventListener('load', function () { window.setTimeout(function () { window.print(); }, {{ (int) ($printDelay ?? 0) }}); });
    </script>
</body>
</html>
