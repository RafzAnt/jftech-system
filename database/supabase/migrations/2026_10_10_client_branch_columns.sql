-- Apply this once in the Supabase SQL Editor for an existing project.
-- Safe to rerun. Does not delete or rewrite existing client records.
ALTER TABLE public.clients
    ADD COLUMN IF NOT EXISTS branch_name varchar(100) NOT NULL DEFAULT 'Balilihan',
    ADD COLUMN IF NOT EXISTS registered_barangay_name varchar(100);

CREATE TABLE IF NOT EXISTS public.internet_plans (
    id bigint generated by default as identity primary key,
    plan_name varchar(100) not null unique,
    speed_mbps integer not null,
    monthly_price numeric(10,2) not null default 0,
    installation_fee numeric(10,2) not null default 0,
    scheduled_monthly_price numeric(10,2),
    scheduled_installation_fee numeric(10,2),
    price_effective_on date,
    description text,
    status varchar(20) not null default 'active',
    archived smallint not null default 0 check (archived in (0, 1)),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

ALTER TABLE public.internet_plans
    ADD COLUMN IF NOT EXISTS installation_fee numeric(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS scheduled_monthly_price numeric(10,2),
    ADD COLUMN IF NOT EXISTS scheduled_installation_fee numeric(10,2),
    ADD COLUMN IF NOT EXISTS price_effective_on date,
    ADD COLUMN IF NOT EXISTS status varchar(20) NOT NULL DEFAULT 'active',
    ADD COLUMN IF NOT EXISTS archived smallint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.internet_plan_price_histories (
    id bigint generated by default as identity primary key,
    internet_plan_id bigint not null references public.internet_plans(id) on delete cascade,
    previous_monthly_price numeric(10,2),
    new_monthly_price numeric(10,2),
    previous_installation_fee numeric(10,2),
    new_installation_fee numeric(10,2),
    change_type varchar(20) not null,
    effective_on date,
    reason text,
    changed_by bigint references public.users(id) on delete set null,
    created_at timestamptz not null default now()
);

