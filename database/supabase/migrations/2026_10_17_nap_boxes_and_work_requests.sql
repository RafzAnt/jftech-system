-- Field work from the employee app. Apply once in the Supabase SQL Editor for an existing project.
-- Safe to rerun. Does not delete any rows.
--
--   * nap_boxes / nap_ports   NAP boxes of a branch and their ports
--   * work_requests           installation and repair requests, with the materials reported at completion
--   * employee_api_tokens     sign-in tokens of the employee app (only a hash is stored)
--   * inventory_requests      request_type (out / return), condition, area used, person in charge
BEGIN;

CREATE TABLE IF NOT EXISTS public.nap_boxes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    branch_name varchar(100) NOT NULL,
    barangay_name varchar(100) NOT NULL,
    location varchar(255),
    total_ports smallint NOT NULL CHECK (total_ports > 0),
    status varchar(20) NOT NULL DEFAULT 'active',
    archived boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT nap_boxes_branch_name_unique UNIQUE (branch_name, name)
);
CREATE INDEX IF NOT EXISTS nap_boxes_branch_barangay_index ON public.nap_boxes (branch_name, barangay_name);

CREATE TABLE IF NOT EXISTS public.nap_ports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nap_box_id bigint NOT NULL REFERENCES public.nap_boxes(id) ON DELETE CASCADE,
    port_number smallint NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'available',
    client_id bigint REFERENCES public.clients(id) ON DELETE SET NULL,
    occupied_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT nap_ports_box_number_unique UNIQUE (nap_box_id, port_number)
);

CREATE TABLE IF NOT EXISTS public.work_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code varchar(30) NOT NULL UNIQUE,
    branch_name varchar(100) NOT NULL,
    employee_id bigint NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
    work_type varchar(20) NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'pending_approval',
    client_id bigint REFERENCES public.clients(id) ON DELETE SET NULL,
    new_client_name varchar(100),
    new_client_phone varchar(20),
    new_client_address text,
    barangay_name varchar(100),
    location text,
    problem_details text,
    nap_box_id bigint REFERENCES public.nap_boxes(id) ON DELETE SET NULL,
    nap_port_id bigint REFERENCES public.nap_ports(id) ON DELETE SET NULL,
    actual_nap_box_id bigint REFERENCES public.nap_boxes(id) ON DELETE SET NULL,
    actual_nap_port_id bigint REFERENCES public.nap_ports(id) ON DELETE SET NULL,
    completion_notes text,
    admin_remarks text,
    submitted_at timestamptz,
    reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    completed_at timestamptz,
    confirmed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    confirmed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS work_requests_branch_status_index ON public.work_requests (branch_name, status);
CREATE INDEX IF NOT EXISTS work_requests_employee_index ON public.work_requests (employee_id);

CREATE TABLE IF NOT EXISTS public.work_request_materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_request_id bigint NOT NULL REFERENCES public.work_requests(id) ON DELETE CASCADE,
    inventory_id bigint REFERENCES public.inventory(id) ON DELETE SET NULL,
    item_name varchar(100) NOT NULL,
    used_quantity integer NOT NULL DEFAULT 0 CHECK (used_quantity >= 0),
    returned_quantity integer NOT NULL DEFAULT 0 CHECK (returned_quantity >= 0),
    damaged_quantity integer NOT NULL DEFAULT 0 CHECK (damaged_quantity >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.employee_api_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
    login_history_id bigint,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz,
    last_used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS employee_api_tokens_employee_index ON public.employee_api_tokens (employee_id);

ALTER TABLE public.inventory_requests
    ADD COLUMN IF NOT EXISTS request_type varchar(10) NOT NULL DEFAULT 'out',
    ADD COLUMN IF NOT EXISTS item_condition varchar(30),
    ADD COLUMN IF NOT EXISTS area_used varchar(150),
    ADD COLUMN IF NOT EXISTS person_in_charge varchar(100);

ALTER TABLE public.nap_boxes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nap_ports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.work_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.work_request_materials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employee_api_tokens ENABLE ROW LEVEL SECURITY;

COMMIT;
