-- Installing a client from the employee app:
--   * NAP boxes and clients get Google coordinates (and a client the mode of payment, IP address and Facebook account);
--   * client_installations is the report an employee files after installing; the branch admin edits and confirms it, and only then
--     the client exists;
--   * client_installation_returns are the items brought back, put back in stock when the admin confirms;
--   * an inventory request remembers the report it was used for (installation_id).
-- Run this once in the Supabase SQL Editor; running it again changes nothing.

begin;

alter table public.nap_boxes
    add column if not exists latitude numeric(10,7),
    add column if not exists longitude numeric(10,7);

alter table public.clients
    add column if not exists latitude numeric(10,7),
    add column if not exists longitude numeric(10,7),
    add column if not exists payment_mode varchar(20),
    add column if not exists ip_address varchar(45),
    add column if not exists facebook_account varchar(150);

create table if not exists public.client_installations (
    id bigint generated by default as identity primary key,
    branch_name varchar(100) not null,
    employee_id bigint not null references public.employees(id) on delete cascade,
    status varchar(20) not null default 'submitted',
    client_name varchar(100) not null,
    contact_number varchar(20) not null,
    email varchar(100),
    barangay_name varchar(100) not null,
    exact_address varchar(255) not null,
    internet_plan_id bigint references public.internet_plans(id) on delete set null,
    payment_mode varchar(20) not null,
    ip_address varchar(45),
    facebook_account varchar(150),
    installation_date date not null,
    latitude numeric(10,7) not null,
    longitude numeric(10,7) not null,
    nap_box_id bigint references public.nap_boxes(id) on delete set null,
    nap_port_id bigint references public.nap_ports(id) on delete set null,
    remarks text,
    admin_remarks text,
    client_id bigint references public.clients(id) on delete set null,
    submitted_at timestamptz,
    reviewed_by bigint references public.users(id) on delete set null,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists client_installations_branch_status_index on public.client_installations (branch_name, status);
create index if not exists client_installations_employee_index on public.client_installations (employee_id);

create table if not exists public.client_installation_returns (
    id bigint generated by default as identity primary key,
    installation_id bigint not null references public.client_installations(id) on delete cascade,
    inventory_id bigint references public.inventory(id) on delete set null,
    item_name varchar(100) not null,
    quantity integer not null check (quantity > 0),
    accepted_quantity integer check (accepted_quantity >= 0),
    item_condition varchar(30),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists client_installation_returns_installation_index on public.client_installation_returns (installation_id);

alter table public.inventory_requests add column if not exists installation_id bigint;
create index if not exists inventory_requests_installation_index on public.inventory_requests (installation_id);

alter table public.client_installations enable row level security;
alter table public.client_installation_returns enable row level security;

commit;
