-- One-time compatibility repair for the Laravel codebase's archived = 0/1 queries.
-- Run this once in Supabase SQL Editor after schema.sql has already been run.
do $$
declare
    current_table text;
    archived_type text;
begin
    foreach current_table in array array['users', 'clients', 'internet_plans', 'inventory', 'payroll']
    loop
        select columns.data_type into archived_type
        from information_schema.columns
        where columns.table_schema = 'public'
          and columns.table_name = current_table
          and columns.column_name = 'archived';

        if archived_type = 'boolean' then
            execute format('alter table public.%I alter column archived drop default', current_table);
            execute format('alter table public.%I alter column archived type smallint using case when archived then 1 else 0 end', current_table);
            execute format('alter table public.%I alter column archived set default 0', current_table);
        end if;
    end loop;
end $$;

create table if not exists public.internet_plan_price_histories (
    id bigint generated by default as identity primary key,
    internet_plan_id bigint not null references public.internet_plans(id) on delete cascade,
    previous_monthly_price numeric(10,2),
    new_monthly_price numeric(10,2),
    previous_installation_fee numeric(10,2),
    new_installation_fee numeric(10,2),
    change_type varchar(20) not null,
    effective_on date,
    reason text,
    changed_by bigint references public.users(id) on delete set null,
    created_at timestamptz not null default now()
);
